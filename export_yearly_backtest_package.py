def simulate_with_withdrawals(
    candidate_df: pd.DataFrame,
    *,
    config,
    symbols: list[str],
    initial_deposit: float,
    dynamic_margin_fraction: float,
    withdrawal_trigger: float,
    first_withdrawal: float,
    followup_withdraw_fraction: float,
    date_range_label: str,
) -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame, dict[str, Any]]:
    guard_settings = regime_guard_settings_from_strategy(config.strategy)
    trackers = {symbol: RegimeGuardTracker(guard_settings) for symbol in symbols}

    trades = candidate_df.copy()
    trades["fill_time_utc"] = pd.to_datetime(trades["fill_time_utc"], utc=True, errors="coerce")
    trades["exit_time_utc"] = pd.to_datetime(trades["exit_time_utc"], utc=True, errors="coerce")
    trades = trades.dropna(subset=["fill_time_utc", "exit_time_utc"]).sort_values(["fill_time_utc", "symbol"]).reset_index(drop=True)

    cash_equity = float(initial_deposit)
    used_margin = 0.0
    total_withdrawn = 0.0
    initial_recovery_done = False
    regime_trigger_count = 0.0
    peak_trading = cash_equity
    peak_total = cash_equity
    max_drawdown_trading = 0.0
    max_drawdown_total = 0.0
    event_index = 0

    events: list[dict[str, Any]] = [
        {
            "event_index": event_index,
            "time": f"{date_range_label[:10]}T00:00:00+00:00",
            "event_type": "start",
            "symbol": "",
            "pnl_account": 0.0,
            "withdrawal_amount": 0.0,
            "trading_equity": round2(cash_equity),
            "total_withdrawn": round2(total_withdrawn),
            "total_value": round2(cash_equity + total_withdrawn),
        }
    ]
    event_index += 1
    withdrawal_rows: list[dict[str, Any]] = []
    portfolio_rows: list[dict[str, Any]] = []
    open_positions: list[dict[str, Any]] = []

    def update_drawdowns() -> None:
        nonlocal peak_trading, peak_total, max_drawdown_trading, max_drawdown_total
        peak_trading = max(peak_trading, cash_equity)
        total_value = cash_equity + total_withdrawn
        peak_total = max(peak_total, total_value)
        if peak_trading > 0:
            max_drawdown_trading = min(max_drawdown_trading, ((cash_equity - peak_trading) / peak_trading) * 100.0)
        if peak_total > 0:
            max_drawdown_total = min(max_drawdown_total, ((total_value - peak_total) / peak_total) * 100.0)

    def maybe_withdraw(after_close_time: pd.Timestamp, symbol: str, cash_before_close: float) -> None:
        nonlocal cash_equity, total_withdrawn, initial_recovery_done, event_index
        crossed = cash_before_close < withdrawal_trigger <= cash_equity
        if not crossed:
            update_drawdowns()
            return

        if not initial_recovery_done:
            withdrawal_amount = min(first_withdrawal, cash_equity)
            withdrawal_kind = "fixed_initial_recovery"
            initial_recovery_done = True
        else:
            withdrawal_amount = cash_equity * followup_withdraw_fraction
            withdrawal_kind = "followup_fractional_withdrawal"

        cash_equity -= withdrawal_amount
        total_withdrawn += withdrawal_amount
        withdrawal_row = {
            "event_index": event_index,
            "time_utc": after_close_time.isoformat(),
            "symbol": symbol,
            "trigger_level": round2(withdrawal_trigger),
            "withdrawal_kind": withdrawal_kind,
            "fixed_withdrawal_amount": round2(first_withdrawal),
            "followup_withdraw_fraction": round2(followup_withdraw_fraction),
            "trading_equity_before_withdrawal": round2(cash_equity + withdrawal_amount),
            "withdrawal_amount": round2(withdrawal_amount),
            "trading_equity_after_withdrawal": round2(cash_equity),
            "total_withdrawn_after_event": round2(total_withdrawn),
        }
        withdrawal_rows.append(withdrawal_row)
        events.append(
            {
                "event_index": event_index,
                "time": after_close_time.isoformat(),
                "event_type": "withdrawal",
                "symbol": symbol,
                "pnl_account": 0.0,
                "withdrawal_amount": round2(withdrawal_amount),
                "trading_equity": round2(cash_equity),
                "total_withdrawn": round2(total_withdrawn),
                "total_value": round2(cash_equity + total_withdrawn),
            }
        )
        event_index += 1
        update_drawdowns()

    def settle_until(cutoff: pd.Timestamp) -> None:
        nonlocal cash_equity, used_margin, open_positions, regime_trigger_count, event_index
        still_open: list[dict[str, Any]] = []
        for position in sorted(open_positions, key=lambda item: item["exit_time_utc"]):
            if position["exit_time_utc"] > cutoff:
                still_open.append(position)
                continue

            cash_before_close = cash_equity
            cash_equity += float(position["pnl_account"])
            used_margin -= float(position["estimated_margin_account"])
            tracker = trackers.get(str(position["symbol"]))
            if tracker is not None:
                did_trigger = tracker.record_trade(
                    position["exit_time_utc"].to_pydatetime().astimezone(dt.timezone.utc),
                    float(position["pnl_account"]),
                )
                if did_trigger:
                    regime_trigger_count += 1.0

            events.append(
                {
                    "event_index": event_index,
                    "time": position["exit_time_utc"].isoformat(),
                    "event_type": "trade_close",
                    "symbol": position["symbol"],
                    "pnl_account": round2(float(position["pnl_account"])),
                    "withdrawal_amount": 0.0,
                    "trading_equity": round2(cash_equity),
                    "total_withdrawn": round2(total_withdrawn),
                    "total_value": round2(cash_equity + total_withdrawn),
                }
            )
            event_index += 1
            maybe_withdraw(position["exit_time_utc"], str(position["symbol"]), cash_before_close)
        open_positions = still_open

    for _, trade in trades.iterrows():
        fill_time = pd.Timestamp(trade["fill_time_utc"])
        exit_time = pd.Timestamp(trade["exit_time_utc"])
        settle_until(fill_time)

        symbol = str(trade["symbol"])
        tracker = trackers.get(symbol)
        fill_dt = fill_time.to_pydatetime().astimezone(dt.timezone.utc)
        guard_blocked = tracker.is_blocked(fill_dt) if tracker is not None else False

        margin_per_unit = to_float(trade.get("margin_per_unit_account"))
        pnl_account_per_unit = to_float(trade.get("pnl_account_per_unit"))
        min_size = to_float(trade.get("min_size"), 0.0) or 0.0
        size_step = to_float(trade.get("size_step"))
        dynamic_target_margin = cash_equity * dynamic_margin_fraction
        available_margin = cash_equity - used_margin

        dynamic_sizing: dict[str, Any] | None = None
        estimated_margin_account = 0.0
        pnl_account = 0.0
        if margin_per_unit is not None and margin_per_unit > 0 and pnl_account_per_unit is not None:
            dynamic_sizing = size_for_target_margin(
                target_margin=dynamic_target_margin,
                margin_per_unit=margin_per_unit,
                min_size=min_size,
                size_step=size_step,
            )
            if dynamic_sizing.get("ok"):
                size = float(dynamic_sizing["size"])
                estimated_margin_account = float(dynamic_sizing["estimated_margin"])
                pnl_account = float(size * pnl_account_per_unit)
            else:
                size = None
        else:
            size = None
            dynamic_sizing = {"ok": False, "reason": "missing sizing inputs"}

        accepted = cash_equity > 0
        skip_reason = ""
        if guard_blocked:
            accepted = False
            skip_reason = "regime_guard_cooldown"
        elif dynamic_sizing is not None and not dynamic_sizing.get("ok"):
            accepted = False
            skip_reason = str(dynamic_sizing.get("reason") or "dynamic_sizing_failed")
        elif available_margin < estimated_margin_account:
            accepted = False
            skip_reason = "insufficient_available_margin"

        row = trade.to_dict()
        row["accepted"] = accepted
        row["skip_reason"] = skip_reason
        row["size"] = size
        row["portfolio_pnl_account"] = pnl_account
        row["estimated_margin_account"] = estimated_margin_account
        row["portfolio_target_margin_account"] = dynamic_target_margin
        row["portfolio_equity_before_account"] = cash_equity
        row["portfolio_used_margin_before_account"] = used_margin
        row["regime_pause_until_utc"] = tracker.pause_until.isoformat() if tracker and tracker.pause_until else ""
        row["regime_recent_trades"] = float(tracker.last_metrics.recent_trades) if tracker is not None else 0.0
        row["regime_recent_win_rate_pct"] = float(tracker.last_metrics.win_rate_pct) if tracker is not None else 0.0
        row["regime_recent_net_pnl"] = float(tracker.last_metrics.net_pnl) if tracker is not None else 0.0
        row["regime_recent_consecutive_losses"] = float(tracker.last_metrics.consecutive_losses) if tracker is not None else 0.0

        if accepted:
            used_margin += estimated_margin_account
            row["portfolio_used_margin_after_open_account"] = used_margin
            open_positions.append(
                {
                    "symbol": symbol,
                    "exit_time_utc": exit_time,
                    "pnl_account": pnl_account,
                    "estimated_margin_account": estimated_margin_account,
                }
            )
        else:
            row["portfolio_used_margin_after_open_account"] = used_margin

        portfolio_rows.append(row)

    settle_until(pd.Timestamp.max.tz_localize("UTC"))

    portfolio_df = pd.DataFrame(portfolio_rows)
    if portfolio_df.empty:
        summary = {
            "Symbols": ",".join(symbols),
            "DateRange": date_range_label,
            "AccountCurrency": "USD",
            "InitialDepositUSD": float(initial_deposit),
            "WithdrawalTriggerUSD": float(withdrawal_trigger),
            "FirstWithdrawalUSD": float(first_withdrawal),
            "FollowupWithdrawalFraction": float(followup_withdraw_fraction),
            "DynamicMarginFraction": float(dynamic_margin_fraction),
            "PriceModel": "Historical bid/ask execution with Friday pre-weekend close and overnight funding",
            "Trades": 0.0,
            "AcceptedTrades": 0.0,
            "SkippedTrades": 0.0,
            "RegimeGuardSkippedTrades": 0.0,
            "RegimeGuardTriggers": 0.0,
            "WinRatePct": 0.0,
            "ProfitFactor": 0.0,
            "NetPnLUSD": 0.0,
            "TotalWithdrawnUSD": 0.0,
            "FinalTradingEquityUSD": float(initial_deposit),
            "EndingTotalValueUSD": float(initial_deposit),
            "ReturnPctOnInitial": 0.0,
            "PeakTradingEquityUSD": float(initial_deposit),
            "PeakTotalValueUSD": float(initial_deposit),
            "MaxDrawdownTradingPct": 0.0,
            "MaxDrawdownTotalValuePct": 0.0,
            "TotalOvernightFundingUSD": 0.0,
        }
        return portfolio_df, pd.DataFrame(events), pd.DataFrame(withdrawal_rows), summary

    accepted_df = portfolio_df[portfolio_df["accepted"].apply(to_bool)].copy()
    wins_df = accepted_df[accepted_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) > 0)].copy()
    losses_df = accepted_df[accepted_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) <= 0)].copy()

    gross_profit = wins_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) or 0.0).sum()
    gross_loss = abs(losses_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) or 0.0).sum())
    total_overnight_funding = accepted_df["overnight_funding_account"].apply(lambda value: to_float(value, 0.0) or 0.0).sum()

    summary = {
        "Symbols": ",".join(symbols),
        "DateRange": date_range_label,
        "AccountCurrency": "USD",
        "InitialDepositUSD": float(initial_deposit),
        "WithdrawalTriggerUSD": float(withdrawal_trigger),
        "FirstWithdrawalUSD": float(first_withdrawal),
        "FollowupWithdrawalFraction": float(followup_withdraw_fraction),
        "DynamicMarginFraction": float(dynamic_margin_fraction),
        "PriceModel": "Historical bid/ask execution with Friday pre-weekend close and overnight funding",
        "Trades": float(len(portfolio_df)),
        "AcceptedTrades": float(len(accepted_df)),
        "SkippedTrades": float(len(portfolio_df) - len(accepted_df)),
        "RegimeGuardSkippedTrades": float((portfolio_df["skip_reason"] == "regime_guard_cooldown").sum()),
        "RegimeGuardTriggers": float(regime_trigger_count),
        "WinRatePct": float((len(wins_df) / len(accepted_df)) * 100.0) if len(accepted_df) else 0.0,
        "ProfitFactor": float(gross_profit / gross_loss) if gross_loss else 0.0,
        "NetPnLUSD": round2(sum(to_float(value, 0.0) or 0.0 for value in accepted_df["portfolio_pnl_account"].tolist())),
        "TotalWithdrawnUSD": round2(total_withdrawn),
        "FinalTradingEquityUSD": round2(cash_equity),
        "EndingTotalValueUSD": round2(cash_equity + total_withdrawn),
        "ReturnPctOnInitial": round2((((cash_equity + total_withdrawn) / initial_deposit) - 1.0) * 100.0) if initial_deposit > 0 else 0.0,
        "PeakTradingEquityUSD": round2(peak_trading),
        "PeakTotalValueUSD": round2(peak_total),
        "MaxDrawdownTradingPct": round2(max_drawdown_trading),
        "MaxDrawdownTotalValuePct": round2(max_drawdown_total),
        "TotalOvernightFundingUSD": round2(total_overnight_funding),
    }
    return portfolio_df, pd.DataFrame(events), pd.DataFrame(withdrawal_rows), summary


def main() -> None:
    args = parse_args()
    config = load_config(args.env_file)

    input_csv = Path(args.input_csv)
    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    candidate_df = pd.read_csv(input_csv)
    date_range_label = f"{args.from_date} -> {args.to_date}"
    portfolio_df, events_df, withdrawals_df, summary = simulate_with_withdrawals(
        candidate_df,
        config=config,
        symbols=args.symbols,
        initial_deposit=args.initial_deposit,
        dynamic_margin_fraction=args.dynamic_margin_fraction,
        withdrawal_trigger=args.withdrawal_trigger,
        first_withdrawal=args.first_withdrawal,
        followup_withdraw_fraction=args.followup_withdraw_fraction,
        date_range_label=date_range_label,
    )

    accepted_df = portfolio_df[portfolio_df["accepted"].apply(to_bool)].copy()
    wins_df = accepted_df[accepted_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) > 0)].copy()
    losses_df = accepted_df[accepted_df["portfolio_pnl_account"].apply(lambda value: to_float(value, 0.0) <= 0)].copy()

    from_token = args.from_date.replace("-", "_")
    to_token = args.to_date.replace("-", "_")
    symbol_token = "_".join(symbol.upper() for symbol in args.symbols)
    prefix = f"yearly_backtest_{from_token}_{to_token}_{symbol_token}"
    if args.name_suffix:
        prefix = f"{prefix}_{args.name_suffix}"
    portfolio_df.to_csv(output_dir / f"{prefix}_trades.csv", index=False)
    accepted_df.to_csv(output_dir / f"{prefix}_real_traded.csv", index=False)
    wins_df.to_csv(output_dir / f"{prefix}_real_wins.csv", index=False)
    losses_df.to_csv(output_dir / f"{prefix}_real_losses.csv", index=False)
    events_df.to_csv(output_dir / f"{prefix}_events.csv", index=False)
    withdrawals_df.to_csv(output_dir / f"{prefix}_withdrawals.csv", index=False)
    (output_dir / f"{prefix}_summary.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (output_dir / f"{prefix}_summary.txt").write_text(render_summary_text(summary), encoding="utf-8")
    render_equity_svg(events_df, output_dir / f"{prefix}.svg", from_date=args.from_date, to_date=args.to_date)


if __name__ == "__main__":
    main()
